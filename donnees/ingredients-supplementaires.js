for (const [rangement, rayon, uniteDefaut, liste] of GROUPES) {
  for (const el of liste) {
    let nom = el;
    let unite = uniteDefaut;
    let options = {};
    if (Array.isArray(el)) {
      nom = el[0];
      if (typeof el[1] === 'string') { unite = el[1]; options = el[2] || {}; } else {
        options = el[1] || {};
        // Un ingrédient qui se compte à la pièce prend l'unité « pc » sauf mention contraire.
        if (options.piece) unite = 'pc';
      }
    }
    INGREDIENTS.push(Object.assign({ id: slug(nom), nom, rangement, rayon, unite }, options));
  }
}

